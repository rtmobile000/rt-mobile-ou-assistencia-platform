create table public.organization_members (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.member_role not null default 'technician',
  created_at timestamptz not null default now(),
  unique (organization_id, user_id)
);

-- Ao criar uma organização, adiciona automaticamente o usuário criador como owner.
-- SECURITY DEFINER permite bootstrap sem abrir uma política de inserção de membros para todos.
create or replace function public.bootstrap_organization_owner()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.organization_members (organization_id, user_id, role)
  values (new.id, new.owner_user_id, 'owner')
  on conflict (organization_id, user_id) do nothing;
  return new;
end;
$$;

create trigger organizations_bootstrap_owner
after insert on public.organizations
for each row execute function public.bootstrap_organization_owner();

